def clean_axis(ax, grid=False):
    for side in ["top", "right"]:
        ax.spines[side].set_visible(False)
    ax.tick_params(length=3, width=0.6)
    if grid:
        ax.grid(axis="x", color=RULE, linewidth=0.6, zorder=0)
        ax.set_axisbelow(True)


def save(fig, name, output, source_frames, caption, dimensions_mm):
    fig.canvas.draw()
    output.mkdir(parents=True, exist_ok=True)
    source_dir = output / "Source_Data"
    source_dir.mkdir(exist_ok=True)
    data_names = []
    for suffix, frame in source_frames.items():
        fname = name + ("_" + suffix if suffix else "") + ".csv"
        frame.to_csv(source_dir / fname, index=False, encoding="utf-8", float_format="%.17g")
        data_names.append("Source_Data/" + fname)
    fig.savefig(output / (name + ".pdf"), format="pdf")
    fig.savefig(output / (name + ".tif"), dpi=600, pil_kwargs={"compression": "tiff_lzw"})
    fig.savefig(output / (name + ".png"), dpi=220)
    CAPTIONS[name] = caption + " " + DISCLOSURE
    QA[name] = {"dimensions_mm": dimensions_mm, "source_data_files": data_names, "data_generated": False, "model_refitted": False, "raster_dpi": 600, "pdf_fonts_embedded": True, "source_checks": "Exact source values retained; transformation formulas documented in caption", "visual_audit": "pending"}
    plt.close(fig)


def matrix(ax, arr, xlabels, ylabels, cmap, norm, formatter, title, negative_outline=False, fontsize=7.3):
    im = ax.imshow(arr, cmap=cmap, norm=norm, interpolation="none", aspect="auto")
    ax.set_xticks(np.arange(len(xlabels)))
    ax.set_xticklabels(xlabels, rotation=55, ha="right", rotation_mode="anchor")
    ax.set_yticks(np.arange(len(ylabels)))
    ax.set_yticklabels(ylabels)
    ax.tick_params(axis="both", length=0, pad=4)
    ax.set_xticks(np.arange(-0.5, len(xlabels), 1), minor=True)
    ax.set_yticks(np.arange(-0.5, len(ylabels), 1), minor=True)
    ax.grid(which="minor", color="white", linewidth=0.8)
    ax.tick_params(which="minor", bottom=False, left=False)
    for spine in ax.spines.values():
        spine.set_visible(False)
    for iy in range(arr.shape[0]):
        for ix in range(arr.shape[1]):
            value = arr[iy, ix]
            rgba = cmap(norm(value))
            luminance = 0.2126 * rgba[0] + 0.7152 * rgba[1] + 0.0722 * rgba[2]
            ax.text(ix, iy, formatter(value), ha="center", va="center", fontsize=fontsize, color="white" if luminance < 0.48 else INK)
            if negative_outline and value < 0:
                ax.add_patch(Rectangle((ix - 0.48, iy - 0.48), 0.96, 0.96, fill=False, edgecolor=ORANGE, linewidth=1.1))
    ax.set_title(title, loc="left", pad=9)
    return im


